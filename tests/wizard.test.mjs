import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require=createRequire(import.meta.url);
const {formatPesos,parsePesos,makeResearchPrompt,summarizeSearch}=require('../dist/wizard.js');
assert.equal(formatPesos('130000000'),'130.000.000');
assert.equal(formatPesos('2.000.000'),'2.000.000');
assert.equal(parsePesos('130.000.000'),130000000);
assert.equal(parsePesos(''),null);
const home=makeResearchPrompt({category:'Vivienda',query:'apartamento en venta',location:'Soacha',min:'80.000.000',max:'130.000.000',rental:'800.000',details:'con ascensor'});
assert.match(home,/130\.000\.000/);assert.match(home,/800\.000/);assert.match(home,/Soacha/);assert.match(home,/con ascensor/);assert.match(home,/Facebook Marketplace/);assert.match(home,/Mercado Libre/);
const consoleTask=makeResearchPrompt({category:'Tecnología',query:'PlayStation 5',location:'Bogotá',min:'',max:'2.000.000',rental:'',details:''});
assert.match(consoleTask,/2\.000\.000/);assert.doesNotMatch(consoleTask,/arriendo/i);
assert.throws(()=>makeResearchPrompt({category:'Tecnología',query:' ',location:'Bogotá'}),/buscas/i);
assert.throws(()=>makeResearchPrompt({category:'Tecnología',query:'consola',location:'Bogotá',min:'2.000.000',max:'1.000.000'}),/mínimo/i);
assert.match(summarizeSearch({category:'Vivienda',query:'apartamento',location:'Soacha',max:'130.000.000'}), /Hasta \$130\.000\.000/);
console.log('Wizard: presupuesto, requisitos y consultas correctos');
const {connectionNext}=require('../dist/wizard.js');
assert.equal(connectionNext({loaded:false}),'wait');
assert.equal(connectionNext({loaded:true,secureControl:false}),'secure');
assert.equal(connectionNext({loaded:true,secureControl:true,authenticated:false}),'authenticate');
assert.equal(connectionNext({loaded:true,secureControl:true,authenticated:true}),'open');
const {validateRadarPassword}=require('../dist/wizard.js');
assert.match(validateRadarPassword('1234567'),/8 caracteres/);
assert.equal(validateRadarPassword('contraseña-segura'),null);
assert.match(validateRadarPassword('x'.repeat(129)),/128 caracteres/);
